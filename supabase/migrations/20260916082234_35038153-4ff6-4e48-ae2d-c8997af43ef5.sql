CREATE TABLE public.puzzles (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code text NOT NULL UNIQUE,
  fen text NOT NULL,
  side_to_move text NOT NULL DEFAULT 'w',
  theme text NOT NULL DEFAULT 'tactics',
  theme_zh text NOT NULL DEFAULT '战术计算',
  theme_en text NOT NULL DEFAULT 'Tactics',
  difficulty integer NOT NULL DEFAULT 1,
  rating integer NOT NULL DEFAULT 1200,
  moves_required integer NOT NULL DEFAULT 1,
  hint_zh text NOT NULL DEFAULT '',
  hint_en text NOT NULL DEFAULT '',
  explanation_zh text NOT NULL DEFAULT '',
  explanation_en text NOT NULL DEFAULT '',
  tp_reward integer NOT NULL DEFAULT 4,
  diamond_reward integer NOT NULL DEFAULT 10,
  created_at timestamp with time zone NOT NULL DEFAULT now(),
  updated_at timestamp with time zone NOT NULL DEFAULT now()
);
GRANT SELECT ON public.puzzles TO anon, authenticated;
GRANT ALL ON public.puzzles TO service_role;
ALTER TABLE public.puzzles ENABLE ROW LEVEL SECURITY;
CREATE POLICY "puzzles_public_read" ON public.puzzles FOR SELECT TO anon, authenticated USING (true);

CREATE TABLE public.puzzle_solutions (
  puzzle_id integer PRIMARY KEY REFERENCES public.puzzles(id) ON DELETE CASCADE,
  solution text[] NOT NULL,
  alternates jsonb NOT NULL DEFAULT '[]'::jsonb,
  created_at timestamp with time zone NOT NULL DEFAULT now(),
  updated_at timestamp with time zone NOT NULL DEFAULT now()
);
GRANT ALL ON public.puzzle_solutions TO service_role;
ALTER TABLE public.puzzle_solutions ENABLE ROW LEVEL SECURITY;
CREATE POLICY "puzzle_solutions_no_client_access" ON public.puzzle_solutions FOR SELECT TO anon, authenticated USING (false);

CREATE TABLE public.puzzle_progress (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  puzzle_id integer NOT NULL REFERENCES public.puzzles(id) ON DELETE CASCADE,
  solved boolean NOT NULL DEFAULT false,
  attempts integer NOT NULL DEFAULT 0,
  best_ms integer,
  reward_granted boolean NOT NULL DEFAULT false,
  solved_at timestamp with time zone,
  created_at timestamp with time zone NOT NULL DEFAULT now(),
  updated_at timestamp with time zone NOT NULL DEFAULT now(),
  UNIQUE (user_id, puzzle_id)
);
GRANT SELECT ON public.puzzle_progress TO authenticated;
GRANT ALL ON public.puzzle_progress TO service_role;
ALTER TABLE public.puzzle_progress ENABLE ROW LEVEL SECURITY;
CREATE POLICY "puzzle_progress_select_own" ON public.puzzle_progress FOR SELECT TO authenticated USING (auth.uid() = user_id);

CREATE TABLE public.puzzle_daily (
  day date PRIMARY KEY,
  puzzle_id integer NOT NULL REFERENCES public.puzzles(id) ON DELETE CASCADE,
  created_at timestamp with time zone NOT NULL DEFAULT now()
);
GRANT SELECT ON public.puzzle_daily TO anon, authenticated;
GRANT ALL ON public.puzzle_daily TO service_role;
ALTER TABLE public.puzzle_daily ENABLE ROW LEVEL SECURITY;
CREATE POLICY "puzzle_daily_public_read" ON public.puzzle_daily FOR SELECT TO anon, authenticated USING (true);

ALTER TABLE public.profiles
  ADD COLUMN IF NOT EXISTS puzzle_streak integer NOT NULL DEFAULT 0,
  ADD COLUMN IF NOT EXISTS puzzle_best_streak integer NOT NULL DEFAULT 0,
  ADD COLUMN IF NOT EXISTS puzzle_last_day date;

CREATE OR REPLACE FUNCTION public.update_updated_at_column()
RETURNS trigger
LANGUAGE plpgsql
SET search_path TO 'public'
AS $$
BEGIN
  NEW.updated_at = now();
  RETURN NEW;
END;
$$;

CREATE TRIGGER update_puzzles_updated_at BEFORE UPDATE ON public.puzzles
  FOR EACH ROW EXECUTE FUNCTION public.update_updated_at_column();
CREATE TRIGGER update_puzzle_progress_updated_at BEFORE UPDATE ON public.puzzle_progress
  FOR EACH ROW EXECUTE FUNCTION public.update_updated_at_column();

-- 每日一题：按日期稳定挑一道题，无题库时返回 null
CREATE OR REPLACE FUNCTION public.pick_daily_puzzle(p_day date)
RETURNS integer
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO 'public'
AS $$
DECLARE v_id integer;
BEGIN
  SELECT puzzle_id INTO v_id FROM public.puzzle_daily WHERE day = p_day;
  IF v_id IS NOT NULL THEN RETURN v_id; END IF;
  SELECT id INTO v_id FROM public.puzzles
  ORDER BY md5(p_day::text || '#' || id::text)
  LIMIT 1;
  IF v_id IS NULL THEN RETURN NULL; END IF;
  INSERT INTO public.puzzle_daily(day, puzzle_id) VALUES (p_day, v_id)
  ON CONFLICT (day) DO NOTHING;
  SELECT puzzle_id INTO v_id FROM public.puzzle_daily WHERE day = p_day;
  RETURN v_id;
END;
$$;
REVOKE EXECUTE ON FUNCTION public.pick_daily_puzzle(date) FROM anon, authenticated, public;
GRANT EXECUTE ON FUNCTION public.pick_daily_puzzle(date) TO service_role;

-- 记录一次作答：首次解出发训练点与钻石，每日一题维护连胜天数
CREATE OR REPLACE FUNCTION public.record_puzzle_result(
  p_user_id uuid,
  p_puzzle_id integer,
  p_correct boolean,
  p_ms integer,
  p_is_daily boolean DEFAULT false,
  p_day date DEFAULT NULL
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO 'public'
AS $$
DECLARE
  pz public.puzzles%ROWTYPE;
  prog public.puzzle_progress%ROWTYPE;
  first_reward boolean := false;
  pr public.profiles%ROWTYPE;
  new_streak integer;
  bonus_tp integer := 0;
  bonus_dia integer := 0;
BEGIN
  SELECT * INTO pz FROM public.puzzles WHERE id = p_puzzle_id;
  IF NOT FOUND THEN RAISE EXCEPTION 'puzzle not found'; END IF;
  SELECT * INTO pr FROM public.profiles WHERE id = p_user_id FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'profile required'; END IF;

  INSERT INTO public.puzzle_progress(user_id, puzzle_id) VALUES (p_user_id, p_puzzle_id)
  ON CONFLICT (user_id, puzzle_id) DO NOTHING;
  SELECT * INTO prog FROM public.puzzle_progress
  WHERE user_id = p_user_id AND puzzle_id = p_puzzle_id FOR UPDATE;

  first_reward := p_correct AND NOT prog.reward_granted;

  UPDATE public.puzzle_progress SET
    attempts = attempts + 1,
    solved = solved OR p_correct,
    best_ms = CASE WHEN p_correct THEN least(coalesce(best_ms, p_ms), p_ms) ELSE best_ms END,
    solved_at = CASE WHEN p_correct AND solved_at IS NULL THEN now() ELSE solved_at END,
    reward_granted = reward_granted OR p_correct,
    updated_at = now()
  WHERE id = prog.id RETURNING * INTO prog;

  new_streak := coalesce(pr.puzzle_streak, 0);
  IF p_is_daily AND p_day IS NOT NULL AND p_correct AND coalesce(pr.puzzle_last_day, date '1970-01-01') <> p_day THEN
    IF pr.puzzle_last_day = p_day - 1 THEN
      new_streak := new_streak + 1;
    ELSE
      new_streak := 1;
    END IF;
    bonus_tp := 3;
    bonus_dia := 15 + least(35, new_streak * 5);
    UPDATE public.profiles SET
      puzzle_streak = new_streak,
      puzzle_best_streak = greatest(coalesce(puzzle_best_streak, 0), new_streak),
      puzzle_last_day = p_day,
      updated_at = now()
    WHERE id = p_user_id;
  ELSIF p_is_daily AND p_day IS NOT NULL AND NOT p_correct
        AND coalesce(pr.puzzle_last_day, date '1970-01-01') < p_day - 1 THEN
    new_streak := 0;
    UPDATE public.profiles SET puzzle_streak = 0, updated_at = now() WHERE id = p_user_id;
  END IF;

  IF first_reward OR bonus_tp > 0 THEN
    UPDATE public.profiles SET
      training_points = training_points + CASE WHEN first_reward THEN pz.tp_reward ELSE 0 END + bonus_tp,
      diamonds = diamonds + CASE WHEN first_reward THEN pz.diamond_reward ELSE 0 END + bonus_dia,
      updated_at = now()
    WHERE id = p_user_id;
  END IF;

  RETURN jsonb_build_object(
    'first_solve', first_reward,
    'attempts', prog.attempts,
    'streak', new_streak,
    'tp', CASE WHEN first_reward THEN pz.tp_reward ELSE 0 END + bonus_tp,
    'diamonds', CASE WHEN first_reward THEN pz.diamond_reward ELSE 0 END + bonus_dia
  );
END;
$$;
REVOKE EXECUTE ON FUNCTION public.record_puzzle_result(uuid, integer, boolean, integer, boolean, date) FROM anon, authenticated, public;
GRANT EXECUTE ON FUNCTION public.record_puzzle_result(uuid, integer, boolean, integer, boolean, date) TO service_role;